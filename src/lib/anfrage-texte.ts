/** Thema-Titel in der Sprache des Formulars */
export const themaTitel = (t: Thema, lang: FormLang) => (lang === "tr" ? THEMEN_TR[t.id] ?? t.titel : t.titel);
/** Dokumentname: deutsch immer (Kerims Preisliste), auf Türkisch mit türkischer Bezeichnung in Klammern, wo sie sicher ist */
export const dokName = (d: Dokument, lang: FormLang) => (lang === "tr" && DOK_TR[d.id] ? `${d.name} (${DOK_TR[d.id]})` : d.name);
